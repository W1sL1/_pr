#include <stdio.h> // printf, scanf
#include <stdlib.h> // malloc, free
#include <limits.h> // LLONG_MAX для константы INF
int main(void) { // ДП: мин. стоимость пути до n и число оптимальных маршрутов
    int n; if (scanf("%d", &n) != 1 || n <= 0) return 0; // читаем длину дорожки
    // Выделяем память под массивы: a — стоимости клеток, minCost — минимальная стоимость пути,
    // ways — количество способов достичь клетки с минимальной стоимостью
    long long *a = (long long *)malloc((n + 1) * sizeof(long long)); // плата за вход в клетку i
    long long *minCost = (long long *)malloc((n + 1) * sizeof(long long)); // лучшая сумма до i
    long long *ways = (long long *)malloc((n + 1) * sizeof(long long)); // сколько путей дают minCost[i]
    if (!a || !minCost || !ways) { // не удалось выделить память
        free(a); free(minCost); free(ways); return 0;} // освободить частично выделенное
    
    // Заполняем массив стоимостей клеток (индексация с 1)
    for (int i = 1; i <= n; i++) scanf("%lld", &a[i]); // a[i]=-1 — клетка запрещена
    
    // Задаем условную бесконечность (достаточно большое число, чтобы избежать переполнения)
    const long long INF = LLONG_MAX / 4; // метка «клетка пока недостижима»
    
    // Инициализируем массивы: стоимость пути — бесконечность, количество способов — 0
    for (int i = 1; i <= n; i++) { // до обработки переходов все недостижимы
        minCost[i] = INF; ways[i] = 0;} // пути нет, способов 0
    
    // Старт: уже в клетке 1, стоимость пути 0, один способ
    minCost[1] = 0; ways[1] = 1; // в 1-ю клетку входим бесплатно
    for (int i = 2; i <= n; i++) { // считаем ответ для каждой клетки по порядку
        if (a[i] == -1) continue; // через эту клетку нельзя пройти
        // Пробуем прыгнуть в i из клеток i-3, i-2, i-1 (шаг d от 1 до 3)
        for (int d = 1; d <= 3; d++) { // прыжок на 1..3 клетки вперёд с p
            int p = i - d; // Номер предыдущей клетки
            if (p < 1) continue; // Не выходим за левую границу
            if (minCost[p] == INF) continue; // в p ещё нельзя оказаться
            // Считаем стоимость пути до i через p
            long long candidate = minCost[p] + a[i]; // платим только за вход в i
            // Если нашли более дешевый путь — обновляем стоимость и сбрасываем счетчик способов
            if (candidate < minCost[i]) { // найден более дешёвый путь
                minCost[i] = candidate; ways[i] = ways[p];} // способы только от нового минимума
            // Если стоимость такая же — добавляем способы
            else if (candidate == minCost[i]) ways[i] += ways[p]; // ещё один равный по цене предшественник
            
        }
    }
    if (minCost[n] == INF) printf("-1\n"); // до финиша не добраться
    else {
        // Выводим минимальную стоимость и количество способов её достичь
        printf("%lld\n", minCost[n]); printf("%lld\n", ways[n]); // стоимость, затем число путей
    }
    free(a); free(minCost); free(ways); return 0; // освобождение и выход
}
