#include <stdio.h>

int main() {
    // 1. Инициализируем два массива случайными нерегулярными числами
    int arr1[10] = {5, 12, 3, 8, 21, 14, 7, 1, 9, 18};
    int arr2[15] = {11, 6, 25, 4, 13, 2, 17, 20, 15, 22, 0, 19, 16, 24, 10};
    
    // 2. Создаем один общий массив на 25 элементов
    int combined[25];
    
    // Копируем первый массив
    for (int i = 0; i < 10; i++) {
        combined[i] = arr1[i];
    }
    // Копируем второй массив (со смещением на 10 позиций)
    for (int i = 0; i < 15; i++) {
        combined[10 + i] = arr2[i];
    }

    // 3. Вводим два числа для поиска
    int num1, num2;
    printf("Введите два числа из массива: ");
    scanf("%d %d", &num1, &num2);

    // Variables для хранения индексов найденных чисел
    int idx1 = -1, idx2 = -1;

    // 4. Ищем индексы введенных чисел в общем массиве
    for (int i = 0; i < 25; i++) {
        if (combined[i] == num1) {
            idx1 = i;
        }
        if (combined[i] == num2) {
            idx2 = i;
        }
    }

    // Проверяем, оба ли числа найдены
    if (idx1 == -1 || idx2 == -1) {
        printf("Ошибка: одно или оба числа не найдены в массиве.\n");
        return 1;
    }

    // 5. Определяем, какое число идет раньше, а какое позже
    int start = (idx1 < idx2) ? idx1 : idx2;
    int end = (idx1 < idx2) ? idx2 : idx1;

    // 6. Выводим элементы, которые находятся строго между ними
    if (end - start <= 1) {
        printf("Между этими числами нет других элементов.\n");
    } else {
        printf("Элементы между ними: ");
        for (int i = start + 1; i < end; i++) {
            printf("%d ", combined[i]);
        }
        printf("\n");
    }

    return 0;
}
