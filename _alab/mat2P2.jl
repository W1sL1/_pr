# Код на julia (анализ кривой второго порядка, человек сам вводит коэффициенты): 
# 1- Матрицы: Составление матрицы квадратичной формы Q (для поиска собственных чисел) 
# и расширенной матрицы QQ (для классификации типа фигуры).
# 2- Инварианты: Вычисление определителей I1, I2, I3. 
# 3- Собственные числа и векторы: Определение угла поворота осей, L1 будет большее число по модулю. 
# 4- Центр: Решение системы линейных уравнений для поиска (x_0,y_0).
# 5- Классификация: Определение типа фигуры по инвариантам {
# Всего 9 типов:
# 1. Эллипс
# 2. Мнимый эллипс
# 3. Точка (пара мнимых пересекающихся прямых)
# 4. Гипербола
# 5. Пара пересекающихся прямых
# 6. Парабола
# 7. Пара параллельных прямых
# 8. Пара мнимых параллельных прямых
# 9. Прямая (совпадающие прямые)
# }.
# 6- Каноническое уравнение: Сборка итоговой формулы {
# f — это свободный член (константа).
# x и y — это новые координаты (переменные).
# p (в уравнении параболы) — это параметр параболы.
# L1 и L2 (лямбда 1 и 2) — это собственные числа матрицы коэффициентов.
# // 1. Эллипс (L1, L2 одного знака, f противоположного)
# L1*x*x + L2*y*y + f = 0; 
# // 2. Мнимый эллипс (L1, L2, f одного знака)
# L1*x*x + L2*y*y + f = 0; 
# // 3. Точка / Пара мнимых пересекающихся прямых (f = 0, L1, L2 одного знака)
# L1*x*x + L2*y*y = 0; 
# // 4. Гипербола (L1, L2 разных знаков, f != 0)
# L1*x*x + L2*y*y + f = 0; 
# // 5. Пара пересекающихся прямых (f = 0, L1, L2 разных знаков)
# L1*x*x + L2*y*y = 0; 
# // 6. Парабола (одно из L = 0, присутствует линейная часть 2*p*y)
# L1*x*x + 2*p*y = 0; 
# // 7. Пара параллельных прямых (L2 = 0, L1 и f разных знаков)
# L1*x*x + f = 0; 
# // 8. Пара мнимых параллельных прямых (L2 = 0, L1 и f одного знака)
# L1*x*x + f = 0; 
# // 9. Прямая / Совпадающие прямые (L2 = 0, f = 0)
# L1*x*x = 0;
# }.

using LinearAlgebra

function analyze_conic()
    println("Введите коэффициенты уравнения Ax^2 + 2Bxy + Cy^2 + 2Dx + 2Ey + F = 0:")
    print("A: "); A = parse(Float64, readline())
    print("B (половина коэффициента при xy): "); B = parse(Float64, readline())
    print("C: "); C = parse(Float64, readline())
    print("D (половина коэффициента при x): "); D = parse(Float64, readline())
    print("E (половина коэффициента при y): "); E = parse(Float64, readline())
    print("F: "); F = parse(Float64, readline())

    # 1. Матрицы
    Q = [A B; B C]
    QQ = [A B D; B C E; D E F]

    # 2. Инварианты
    I1 = tr(Q)          # A + C
    I2 = det(Q)         # AC - B^2
    I3 = det(QQ)

    # 3. Собственные числа и угол
    evals = eigvals(Q)
    # Сортируем так, чтобы L1 было больше по модулю
    if abs(evals[1]) < abs(evals[2])
        L1, L2 = evals[2], evals[1]
    else
        L1, L2 = evals[1], evals[2]
    end

    alpha = 0.5 * atan(2B, A - C)
    println("\nИнварианты: I1=$I1, I2=$I2, I3=$I3")
    println("Собственные числа: L1=$L1, L2=$L2")
    println("Угол поворота: $(rad2deg(alpha))°")

    # 4. Центр и 5. Классификация
    type_name = ""
    canonical_eq = ""

    if I2 > 0  # Эллиптический тип
        x0, y0 = Q \ [-D, -E]
        f = I3 / I2
        if I3 != 0
            if I1 * I3 < 0
                type_name = "Эллипс"
            else
                type_name = "Мнимый эллипс"
            end
            canonical_eq = "$(L1)x² + $(L2)y² + $f = 0"
        else
            type_name = "Точка (пари мнимых пересекающихся прямых)"
            canonical_eq = "$(L1)x² + $(L2)y² = 0"
        end
        println("Центр: ($x0, $y0)")

    elseif I2 < 0 # Гиперболический тип
        x0, y0 = Q \ [-D, -E]
        f = I3 / I2
        if I3 != 0
            type_name = "Гипербола"
            canonical_eq = "$(L1)x² + $(L2)y² + $f = 0"
        else
            type_name = "Пара пересекающихся прямых"
            canonical_eq = "$(L1)x² + $(L2)y² = 0"
        end
        println("Центр: ($x0, $y0)")

    else # Параболический тип (I2 == 0)
        if I3 != 0
            type_name = "Парабола"
            # Параметр p = sqrt(-I3/L1^3)
            p = sqrt(abs(I3) / L1^3)
            canonical_eq = "$(L1)x² + 2*($p)y = 0"
        else
            # Ищем инвариант K (корни уравнения для параллельных прямых)
            # В упрощенном виде проверяем f = F - (D^2+E^2)/I1 (если применимо)
            # Для вырожденных случаев используем метод Лагранжа или перенос
            f_val = F - (D^2 + E^2) / I1 # упрощенно для параболического случая
            if f_val * I1 < 0
                type_name = "Пара параллельных прямых"
            elseif f_val * I1 > 0
                type_name = "Пара мнимых параллельных прямых"
            else
                type_name = "Прямая (совпадающие прямые)"
            end
            canonical_eq = "$(L1)x² + ($f_val) = 0"
        end
    end

    println("\nРезультат:")
    println("Тип фигуры: $type_name")
    println("Каноническое уравнение: $canonical_eq")
end

analyze_conic()
