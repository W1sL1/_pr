




#include <stdio.h>
#include <stdlib.h> // Необходима для malloc и free
int main() {
    int n = 10; // Размер массива
    
    // Выделяем память под 10 элементов типа int
    int *a = malloc(n * sizeof(int));
    
    // Проверяем, успешно ли выделилась память
    if (a == NULL) {
        printf("Ошибка выделения памяти!\n");
        return 1;
    }
    printf("Введите %d чисел:\n", n);
    // В C индексация массивов начинается с 0, поэтому цикл идет от 0 до n-1
    for (int i = 0; i < n; i++) {
        scanf("%d", &a[i]); // Считываем элемент (передаем адрес &a[i])
    }
    printf("Вы ввели следующие числа:\n");
    for (int i = 0; i < n; i++) {
        printf("%d ", a[i]); // Выводим элементы через пробел
    }
    printf("\n");
    // Обязательно освобождаем память после использования
    free(a); 
    return 0;
}
