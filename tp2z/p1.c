// malloc (memory allocation)Назначение: Выделяет блок памяти указанного размера в байтах.Особенности: Не очищает и не обнуляет выделенную память. Внутри неё находится «мусор» (случайные значения, которые там лежали ранее).Пример: int *p = (int *)malloc(10 * sizeof(int)); (выделяет память под 10 целых чисел). 
// calloc (contiguous allocation)Назначение: Выделяет память для массива элементов и сразу заполняет её нулями.Особенности: Принимает два аргумента: количество элементов и размер одного элемента. Работает чуть медленнее malloc из-за обязательной нулевой инициализации.Пример: int *p = (int *)calloc(10, sizeof(int)); (выделяет память под 10 чисел и обнуляет их)
// realloc (re-allocation)Назначение: Изменяет размер уже ранее выделенного блока памяти, сохраненного в указателе.Особенности: Может оставить память на прежнем месте (если рядом есть свободное место) или перенести блок в другое место, скопировав туда старые данные. Старый указатель после этого использовать нельзя.Пример: p = (int *)realloc(p, 20 * sizeof(int)); (увеличивает размер памяти под 20 чисел)
