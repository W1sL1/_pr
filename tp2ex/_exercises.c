#include <stdio.h>
#include <stdlib.h> // Необходима для функций malloc и free
int main() {
    // 1. Выделение динамической памяти для 10 элементов типа int
    int *array = (int *)malloc(10 * sizeof(int));
    // Проверка, успешно ли выделилась память
    if (array == NULL) {
        printf("Ошибка выделения памяти!\n");
        return 1;
    }
    // 2. Цикл: заполняем массив числами от 0 до 9 и выводим их
    for (int i = 0; i < 10; i++) {
        array[i] = i * 10; // Заполнение (например, шагом в 10)
        printf("array[%d] = %d\n", i, array[i]);
    }
    // 3. Освобождение выделенной памяти
    free(array);
    array = NULL; // Хорошая практика: зануляем указатель после free
    return 0;
}
