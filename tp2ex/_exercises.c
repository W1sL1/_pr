#include <stdio.h>
// Рекурсивная функция для расчета факториала
unsigned long long factorial(int n) {
    // Базовый случай: 0! = 1 и 1! = 1
    if (n <= 1) {
        return 1;
    }
    // Рекурсивный шаг: n! = n * (n - 1)!
    return n * factorial(n - 1);
}
int main() {
    int number = 5;
    unsigned long long result = factorial(number);
    
    printf("Факториал %d равен %llu\n", number, result);
    return 0;
}
