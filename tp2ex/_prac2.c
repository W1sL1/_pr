// создать массив из 5 структур маллок и тд, заполнение структуры через цикл си, наглядный пример в одном коде 

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
// Объявление структуры
typedef struct {
    int   id;
    char  name[32];
    float salary;
} Employee;
int main(void)
{
    const int N = 5;
    // 1. Выделяем память под массив из 5 структур
    Employee *arr = (Employee *)malloc(N * sizeof(Employee));
    if (arr == NULL) {
        fprintf(stderr, "Ошибка выделения памяти\n");
        return 1;
    }
    // 2. Заполнение структуры через цикл
    for (int i = 0; i < N; i++) {
        arr[i].id = i + 1;
        snprintf(arr[i].name, sizeof(arr[i].name), "Сотрудник_%d", i + 1);
        arr[i].salary = 30000.0f + i * 5000.0f;
    }
    // 3. Вывод содержимого массива
    printf("=== Список сотрудников ===\n");
    for (int i = 0; i < N; i++) {
        printf("ID: %d | Имя: %-14s | Зарплата: %.2f\n",
        arr[i].id, arr[i].name, arr[i].salary);
    }
    // 4. Освобождаем память
    free(arr);
    arr = NULL;
    return 0;
}
// typedef struct — объявляем тип Employee, чтобы не писать struct Employee каждый раз.
// malloc(N * sizeof(Employee)) — выделяем один непрерывный блок памяти под 5 структур. arr — указатель на первый элемент.
// Проверка arr == NULL — обязательно, иначе при неудаче будет segfault.
// Цикл заполнения — обращаемся к элементам как arr[i].поле (можно и (arr + i)->поле).
// snprintf — безопасно формируем строку в char name[32].
// free(arr) — освобождаем память, чтобы не было утечки.
