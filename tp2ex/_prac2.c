// Структура и Юнион в C — минимальный наглядный пример
#include <stdio.h>
// Структура: каждое поле занимает СВОЮ память
struct Point {
    int x;      // 4 байта
    int y;      // 4 байта
};              // итого: 8 байт
// Юнион: все поля делят ОДНУ память (перезаписывают друг друга)
union Value {
    int   i;    // 4 байта
    float f;    // 4 байта
    char  c;    // 1 байт
};              // итого: 4 байта (размер самого большого поля)
int main() {
    struct Point p = {10, 20};
    printf("struct: x=%d y=%d, size=%zu\n", p.x, p.y, sizeof(p));
    // struct: x=10 y=20, size=8   — оба поля живут одновременно

    union Value v;
    v.i = 65;
    printf("union as int:   %d\n", v.i);   // 65
    printf("union as char:  %c\n", v.c);   // 'A' (тот же байт!)
    v.f = 3.14f;                            // перезаписали память
    printf("union as float: %f\n", v.f);   // 3.140000
    printf("union as int:   %d\n", v.i);   // мусор — int затёрт
    printf("union size=%zu\n", sizeof(v)); // 4
}
// Ключевая разница
// struct	union
// Память	сумма всех полей	размер наибольшего поля
// Доступ	все поля одновременно	только одно «живое» в момент времени
// Аналогия	список полей в анкете	одна коробка, куда кладут разные вещи по очереди




